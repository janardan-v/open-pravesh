const clientId = 'your-registered-client-id';
const clientSecret = 'your-client-secret'; // Backend confidential secret

const config = await client.discovery(
  server,
  clientId,
  clientSecret,
);

// 2. Build PKCE-Protected Authorization URL
const code_verifier = client.randomPKCECodeVerifier();
const code_challenge = await client.calculatePKCECodeChallenge(code_verifier);
const state = client.randomState();

const authUrl = client.buildAuthorizationUrl(config, {
  redirect_uri: 'https://client-app.example/callback',
  scope: 'openid profile email',
  code_challenge,
  code_challenge_method: 'S256',
  state,
});
// Redirect user agent: response.redirect(authUrl.href);

// 3. Exchange Authorization Code for RS256 Signed Tokens
